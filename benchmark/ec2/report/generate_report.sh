#!/usr/bin/env bash
# generate_report.sh <run_dir>
# Reads all summary.txt files under run_dir and emits a markdown report.
set -euo pipefail

RUN_DIR="${1:?Usage: generate_report.sh <run_dir>}"
META="$RUN_DIR/run_meta.txt"

kv() { grep -m1 "^$1=" "$META" 2>/dev/null | cut -d= -f2 || echo "?"; }

RUN_ID=$(kv run_id)
TS=$(kv timestamp_utc)
TARGETS=$(kv targets)
QUERIES=$(kv queries)

# Collect all summary files
mapfile -t SUMMARIES < <(find "$RUN_DIR" -name summary.txt | sort)

# Extract unique targets and query types from found summaries
mapfile -t TARGET_LIST < <(printf '%s\n' "${SUMMARIES[@]}" | xargs -I{} dirname {} | xargs -I{} basename {} | awk -F_ '{print $1}' | sort -u)
mapfile -t QUERY_LIST  < <(printf '%s\n' "${SUMMARIES[@]}" | xargs -I{} dirname {} | xargs -I{} basename {} | awk -F_ '{print $2}' | sort -u)

get_val() {
  local target="$1" query="$2" field="$3"
  local f="$RUN_DIR/${target}_${query}/summary.txt"
  [[ -f "$f" ]] && grep -m1 "^${field}=" "$f" | cut -d= -f2 || echo "—"
}

# Header
cat <<EOF
# PgGateway Benchmark Report

**Run ID:** \`$RUN_ID\`
**Date:** $TS
**Targets:** $TARGETS
**Queries:** $QUERIES
**Config:** clients=$(kv clients)  duration=$(kv duration_sec)s  scale=$(kv scale)  pool_mode=$(kv pool_mode)  pool_size=$(kv pool_size)

---

EOF

# Per-query table
for query in "${QUERY_LIST[@]}"; do
  case "$query" in
    tpcb)   qdesc="TPC-B (pgbench default — mixed read/write)" ;;
    simple) qdesc="Simple SELECT (SELECT 1 — pure overhead)" ;;
    sleep)  qdesc="Sleep $(kv sleep_ms)ms (pool queueing under held connections)" ;;
    large)  qdesc="Large Result (5000 rows/query — data transfer)" ;;
    write)  qdesc="Write Heavy (INSERT — high write throughput)" ;;
    lookup) qdesc="Point Lookup (indexed SELECT — max TPS)" ;;
    *)      qdesc="$query" ;;
  esac

  echo "## $qdesc"
  echo ""

  # Build header row
  printf "| %-22s |" "Metric"
  for t in "${TARGET_LIST[@]}"; do printf " %-14s |" "$t"; done
  echo ""

  # Separator
  printf "|%-24s|" "$(printf -- '-%.0s' {1..24})"
  for t in "${TARGET_LIST[@]}"; do printf "%-16s|" "$(printf -- '-%.0s' {1..16})"; done
  echo ""

  # Rows
  for field in tps latency_avg_ms latency_stddev_ms p50_ms p95_ms p99_ms p999_ms transactions failed; do
    case "$field" in
      tps)              label="TPS" ;;
      latency_avg_ms)   label="Avg latency (ms)" ;;
      latency_stddev_ms) label="Latency stddev (ms)" ;;
      p50_ms)           label="p50 (ms)" ;;
      p95_ms)           label="p95 (ms)" ;;
      p99_ms)           label="p99 (ms)" ;;
      p999_ms)          label="p99.9 (ms)" ;;
      transactions)     label="Transactions" ;;
      failed)           label="Failed" ;;
    esac
    printf "| %-22s |" "$label"
    for t in "${TARGET_LIST[@]}"; do
      printf " %-14s |" "$(get_val "$t" "$query" "$field")"
    done
    echo ""
  done

  echo ""

  # Winner callout (by TPS)
  local best_tps=0 best_target=""
  for t in "${TARGET_LIST[@]}"; do
    local tps
    tps=$(get_val "$t" "$query" tps)
    [[ "$tps" == "—" ]] && continue
    if (( $(echo "$tps > $best_tps" | bc -l 2>/dev/null || echo 0) )); then
      best_tps="$tps"
      best_target="$t"
    fi
  done
  [[ -n "$best_target" ]] && echo "> **Highest TPS:** $best_target ($best_tps)"
  echo ""
  echo "---"
  echo ""
done

# System metrics summary (CPU averages from vmstat logs)
echo "## EC2 System Metrics (avg during benchmark)"
echo ""
echo "| Machine  | Avg CPU% | Max CPU% | Avg Mem Used% |"
echo "|----------|----------|----------|---------------|"

for role in client pooler pg; do
  # Try to parse vmstat logs from any scenario (take first one found)
  local vmstat_log
  vmstat_log=$(find "$RUN_DIR" -path "*/${role}_data/*/os/vmstat.log" | head -1 2>/dev/null || true)
  if [[ -n "$vmstat_log" && -f "$vmstat_log" ]]; then
    read -r avg_cpu max_cpu <<< "$(awk 'NR>2 && NF>=16 {
      idle=$15; cpu=100-idle; sum+=cpu; if(cpu>max) max=cpu; n++
    } END { printf "%.1f %.1f", (n?sum/n:0), max }' "$vmstat_log")"
    printf "| %-8s | %-8s | %-8s | %-13s |\n" "$role" "${avg_cpu}%" "${max_cpu}%" "N/A"
  else
    printf "| %-8s | %-8s | %-8s | %-13s |\n" "$role" "N/A" "N/A" "N/A"
  fi
done

echo ""
echo "---"
echo ""
echo "*Report generated by \`generate_report.sh\`. Raw results in: \`$RUN_DIR\`*"
